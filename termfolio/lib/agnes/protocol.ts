/**
 * Provider-neutral protocol types used by the Agnes adapter and the terminal UI.
 *
 * The browser only talks to our own `/api/agnes/chat` route. These types are
 * deliberately independent of Next.js so they can also be used by scripts or
 * another server adapter later.
 */

export type AIMessageRole = "system" | "user" | "assistant" | "tool"

export type AIMessage = {
  role: AIMessageRole
  content: string
  name?: string
  toolCallId?: string
}

export type AIBlock =
  | { type: "text"; text: string }
  | { type: "markdown"; content: string }
  | { type: "code"; code: string; content?: string; language?: string }
  | { type: "json"; data: unknown; schema?: string }
  | { type: "table"; columns: string[]; rows: unknown[][] }
  | { type: "chart"; option: Record<string, unknown>; kind?: "line" | "bar" | "pie" }
  | { type: "image"; url: string; alt?: string }
  | { type: "status"; label: string; state: "idle" | "running" | "info" | "warning" | "success" | "error" }
  | { type: "source"; title: string; url: string; excerpt?: string; domain?: string }
  | { type: "metric"; label: string; value: string | number; unit?: string; trend?: string; help?: string }
  | { type: "artifact"; kind: "html" | "svg" | "mermaid"; content: string; title?: string }
  | { type: "citation"; title?: string; url: string; text?: string }
  | { type: "tool-call"; id?: string; name: string; arguments?: unknown }
  | { type: "error"; code: string; message: string }

export type AIResponseError = {
  code: string
  message: string
  retryable: boolean
}

export type AIUsage = {
  promptTokens?: number
  completionTokens?: number
  totalTokens?: number
  /** Aliases used by the provider-neutral skill protocol. */
  inputTokens?: number
  outputTokens?: number
}

export type AIResponse = {
  /** Provider response id, when the provider supplies one. */
  id?: string
  /** A request id generated by our adapter when the provider has none. */
  requestId?: string
  model: string
  status: "success" | "partial" | "error"
  text: string
  blocks: AIBlock[]
  usage?: AIUsage
  createdAt?: number
  finishReason?: string
  error?: AIResponseError
  raw?: unknown
}

export type ChatCompletionRequest = {
  messages: AIMessage[]
  model?: string
  temperature?: number
  maxTokens?: number
  stream?: boolean
  metadata?: Record<string, string>
}

export type ChatCompletionResult = AIResponse & {
  /** Compatibility alias for route/UI code that expects `{ message }`. */
  message: string
}

export type AgnesWireMessage = {
  role: AIMessageRole
  content: string
  name?: string
  tool_call_id?: string
}

export type AgnesWireResponse = {
  id?: unknown
  model?: unknown
  created?: unknown
  choices?: unknown
  usage?: unknown
}

function asRecord(value: unknown): Record<string, unknown> | undefined {
  return value && typeof value === "object" ? (value as Record<string, unknown>) : undefined
}

const MAX_BLOCK_TEXT = 200_000

function boundedString(value: unknown, max = MAX_BLOCK_TEXT): string | undefined {
  return typeof value === "string" && value.length <= max ? value : undefined
}

function boundedValue(value: unknown, max = MAX_BLOCK_TEXT): boolean {
  try {
    return JSON.stringify(value).length <= max
  } catch {
    return false
  }
}

/**
 * Validate provider/application blocks before handing them to a renderer.
 * Unknown or malformed blocks are dropped locally; model output never becomes
 * executable markup or an unbounded UI payload.
 */
export function parseAIBlocks(value: unknown): AIBlock[] {
  if (!Array.isArray(value)) return []
  const result: AIBlock[] = []

  for (const candidate of value) {
    const block = asRecord(candidate)
    if (!block || typeof block.type !== "string") continue
    switch (block.type) {
      case "text": {
        const text = boundedString(block.text)
        if (text) result.push({ type: "text", text })
        break
      }
      case "markdown": {
        const content = boundedString(block.content)
        if (content) result.push({ type: "markdown", content })
        break
      }
      case "code": {
        const code = boundedString(block.code ?? block.content)
        if (code) {
          const language = boundedString(block.language, 80)
          result.push({ type: "code", code, ...(language ? { language } : {}) })
        }
        break
      }
      case "json":
        if (boundedValue(block.data)) result.push({ type: "json", data: block.data, ...(boundedString(block.schema, 200) ? { schema: boundedString(block.schema, 200) } : {}) })
        break
      case "table": {
        const columns = Array.isArray(block.columns) ? block.columns.filter((item): item is string => typeof item === "string").slice(0, 100) : []
        const rows = Array.isArray(block.rows) ? block.rows.filter((row): row is unknown[] => Array.isArray(row)).slice(0, 1_000) : []
        if (columns.length || rows.length) result.push({ type: "table", columns, rows })
        break
      }
      case "chart": {
        const option = asRecord(block.option ?? block.data)
        if (option && boundedValue(option)) {
          const kind = block.kind === "line" || block.kind === "bar" || block.kind === "pie" ? block.kind : undefined
          result.push({ type: "chart", option, ...(kind ? { kind } : {}) })
        }
        break
      }
      case "image": {
        const url = boundedString(block.url, 2_000)
        if (url) {
          const alt = boundedString(block.alt, 300)
          result.push({ type: "image", url, ...(alt ? { alt } : {}) })
        }
        break
      }
      case "status": {
        const label = boundedString(block.label, 1_000)
        const state = block.state
        if (label && (state === "idle" || state === "running" || state === "info" || state === "warning" || state === "success" || state === "error")) result.push({ type: "status", label, state })
        break
      }
      case "source": {
        const title = boundedString(block.title, 500)
        const url = boundedString(block.url, 2_000)
        if (title && url) {
          const excerpt = boundedString(block.excerpt, 2_000)
          const domain = boundedString(block.domain, 200)
          result.push({ type: "source", title, url, ...(excerpt ? { excerpt } : {}), ...(domain ? { domain } : {}) })
        }
        break
      }
      case "metric": {
        const label = boundedString(block.label, 300)
        const value = typeof block.value === "string" || typeof block.value === "number" ? block.value : undefined
        if (label && value !== undefined) {
          const unit = boundedString(block.unit, 80)
          const trend = boundedString(block.trend, 200)
          const help = boundedString(block.help, 500)
          result.push({ type: "metric", label, value, ...(unit ? { unit } : {}), ...(trend ? { trend } : {}), ...(help ? { help } : {}) })
        }
        break
      }
      case "artifact": {
        const content = boundedString(block.content, 100_000)
        const kind = block.kind
        if (content && (kind === "html" || kind === "svg" || kind === "mermaid")) {
          const title = boundedString(block.title, 300)
          result.push({ type: "artifact", kind, content, ...(title ? { title } : {}) })
        }
        break
      }
      case "citation": {
        const url = boundedString(block.url, 2_000)
        if (url) {
          const title = boundedString(block.title, 500)
          const text = boundedString(block.text, 2_000)
          result.push({ type: "citation", url, ...(title ? { title } : {}), ...(text ? { text } : {}) })
        }
        break
      }
      case "tool-call": {
        const name = boundedString(block.name, 200)
        if (name && boundedValue(block.arguments, 100_000)) result.push({ type: "tool-call", name, ...(boundedString(block.id, 200) ? { id: boundedString(block.id, 200) } : {}), arguments: block.arguments })
        break
      }
      case "error": {
        const code = boundedString(block.code, 120)
        const message = boundedString(block.message, 2_000)
        if (code && message) result.push({ type: "error", code, message })
        break
      }
      default:
        break
    }
  }
  return result
}

function readTextContent(value: unknown): string {
  if (typeof value === "string") return value
  if (!Array.isArray(value)) return ""

  return value
    .map((part) => {
      const record = asRecord(part)
      return typeof record?.text === "string" ? record.text : ""
    })
    .join("")
}

/** Convert an OpenAI-compatible chat completion into the UI-neutral shape. */
export function normalizeAgnesResponse(
  payload: unknown,
  fallbackModel: string,
  requestId?: string,
): ChatCompletionResult {
  const root = asRecord(payload)
  const directText = readTextContent(root?.message ?? root?.text ?? root?.content).trim()
  const nested = asRecord(root?.response)

  // Our own `/api/agnes/chat` intentionally returns a small `{ message, model }`
  // envelope. Accept it here as well as a provider completion so the browser
  // client and the server client share one response contract.
  if (directText) {
    const directModel = typeof root?.model === "string" && root.model.trim() ? root.model : fallbackModel
    const directId = typeof root?.id === "string" ? root.id : undefined
    const directRequestId = typeof root?.requestId === "string" ? root.requestId : requestId || directId
    const nestedBlocks = parseAIBlocks(asRecord(root?.response)?.blocks)
    return {
      id: directId,
      requestId: directRequestId,
      model: directModel,
      status: "success",
      text: directText,
      message: directText,
      blocks: nestedBlocks.length ? nestedBlocks : [{ type: "text", text: directText }],
    }
  }
  if (nested) {
    const nestedRequestId = typeof root?.requestId === "string" ? root.requestId : requestId
    return normalizeAgnesResponse(nested, fallbackModel, nestedRequestId)
  }

  const choices = Array.isArray(root?.choices) ? root.choices : []
  const firstChoice = asRecord(choices[0])
  const message = asRecord(firstChoice?.message)
  const text = readTextContent(message?.content ?? firstChoice?.text).trim()
  const usageRecord = asRecord(root?.usage)
  const usage: AIUsage | undefined = usageRecord
    ? {
        promptTokens: typeof usageRecord.prompt_tokens === "number" ? usageRecord.prompt_tokens : undefined,
        completionTokens:
          typeof usageRecord.completion_tokens === "number" ? usageRecord.completion_tokens : undefined,
        totalTokens: typeof usageRecord.total_tokens === "number" ? usageRecord.total_tokens : undefined,
        inputTokens: typeof usageRecord.prompt_tokens === "number" ? usageRecord.prompt_tokens : undefined,
        outputTokens: typeof usageRecord.completion_tokens === "number" ? usageRecord.completion_tokens : undefined,
      }
    : undefined

  const model = typeof root?.model === "string" && root.model.trim() ? root.model : fallbackModel
  const id = typeof root?.id === "string" ? root.id : undefined
  const resolvedRequestId = requestId || id
  const blocks: AIBlock[] = text ? [{ type: "text", text }] : []

  return {
    id,
    requestId: resolvedRequestId,
    model,
    status: "success",
    text,
    message: text,
    blocks,
    usage,
    createdAt: typeof root?.created === "number" ? root.created : undefined,
    finishReason: typeof firstChoice?.finish_reason === "string" ? firstChoice.finish_reason : undefined,
  }
}

export function toAgnesWireMessages(messages: AIMessage[]): AgnesWireMessage[] {
  return messages.map((message) => ({
    role: message.role,
    content: message.content,
    ...(message.name ? { name: message.name } : {}),
    ...(message.toolCallId ? { tool_call_id: message.toolCallId } : {}),
  }))
}
